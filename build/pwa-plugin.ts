import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import type { Plugin } from 'vite'

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f)
    return statSync(p).isDirectory() ? walk(p) : [p]
  })
}

/**
 * Minimal offline support without extra dependencies: once the build is written we scan the
 * output folder (this also catches worker bundles and the MuPDF WASM) and emit `sw.js`, which
 * precaches every file except the OCR engine and language data (~35 MB, of which a browser
 * needs one core variant and one or two languages): those are cached the first time OCR runs.
 */
export function pwa(): Plugin {
  let outDir = 'dist'
  return {
    name: 'free-pdf-editor-pwa',
    apply: 'build',
    configResolved(c) {
      outDir = resolve(c.root, c.build.outDir)
    },
    closeBundle() {
      const files = walk(outDir)
        .map((f) => relative(outDir, f).split('\\').join('/'))
        .filter((f) => !f.endsWith('.map') && f !== 'sw.js' && !f.startsWith('tesseract/'))
        .sort()
      const hash = createHash('sha256')
      for (const f of files) hash.update(f).update(readFileSync(join(outDir, f)))
      const precache = ['./', ...files.map((f) => `./${f}`)]
      writeFileSync(join(outDir, 'sw.js'), swSource(hash.digest('hex').slice(0, 12), precache))
    },
  }
}

function swSource(version: string, precache: string[]) {
  return `// generated by build/pwa-plugin.ts
const VERSION = ${JSON.stringify(version)}
const APP_CACHE = 'app-' + VERSION
const RUNTIME_CACHE = 'runtime-v1'
const PRECACHE = ${JSON.stringify(precache)}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(APP_CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('app-') && k !== APP_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

async function cacheFirst(request) {
  const hit = await caches.match(request)
  if (hit) return hit
  const res = await fetch(request)
  if (res.ok || res.type === 'opaque') {
    const copy = res.clone()
    caches.open(RUNTIME_CACHE).then((c) => c.put(request, copy))
  }
  return res
}

self.addEventListener('fetch', (event) => {
  const req = event.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (req.mode === 'navigate') {
    event.respondWith(fetch(req).catch(() => caches.match('./index.html')))
    return
  }
  // everything the app needs is self-hosted; other origins pass through untouched
  if (url.origin === self.location.origin) {
    event.respondWith(cacheFirst(req))
  }
})
`
}
